"""plan.txt —— 自建提交器的唯一输入（probe/npu_run.c 读它，不再重编 C）。

格式刻意做成 key=value 纯文本：换算子/换形状/换长度都只是改数据。
写/读都在这里，C 侧与 Python 侧的字段名因此只有一个权威定义。

尺寸字段有两条路（C 侧同名逻辑，见 probe/npu_run.c 的 plan 注释）：
  * `bytes_a/bytes_b/bytes_out` —— 每块缓冲各自的字节数（推荐）；
  * `n_elems` —— 老写法，A/B/C 同尺寸时用，C 侧在没给 bytes_* 时回退到它。
FC 必须用前者：A[M,K]、W[N,K]、C[M,N] 是三个不同的字节数。
"""
from pathlib import Path

from .errors import NpuLibError

FIELDS = (
    "asset_dir", "old_a", "old_b", "old_c",
    "alloc_a", "alloc_b", "alloc_c",
    "dir0", "dir1", "dir2",
    "patch_idx", "expect_patches",
    "n_elems", "bytes_a", "bytes_b", "bytes_out",
    "n_inputs", "in_a", "in_b", "out", "extra_file",
)


class Plan:
    def __init__(self, **kw):
        self.asset_dir = kw["asset_dir"]
        self.old_iova = (kw["old_a"], kw["old_b"], kw["old_c"])
        self.alloc = (kw.get("alloc_a", 4096), kw.get("alloc_b", 4096), kw.get("alloc_c", 4096))
        self.dir = (kw.get("dir0", 1), kw.get("dir1", 2), kw.get("dir2", 1))
        self.patch_idx = kw.get("patch_idx", 2)
        self.expect_patches = kw.get("expect_patches", 3)
        self.n_elems = int(kw.get("n_elems", 0))
        # 每块缓冲的字节数：没显式给就从 n_elems 推（老资产的 plan 仍是这个形状）
        self.bytes_a = int(kw.get("bytes_a", 0)) or self.n_elems
        self.bytes_b = int(kw.get("bytes_b", 0)) or self.n_elems
        self.bytes_out = int(kw.get("bytes_out", 0)) or self.n_elems
        self.n_inputs = int(kw.get("n_inputs", 2))
        self.in_a = kw["in_a"]
        self.in_b = kw.get("in_b", "")
        self.out = kw["out"]
        self.extra_file = kw.get("extra_file", "")

    @classmethod
    def from_asset(cls, asset_dir, iova_txt, **kw):
        """旧 IOVA 永远从资产目录的 iova.txt 读：它与命令流是**同一次抓取**的配对数据。"""
        txt = Path(iova_txt).read_text().split()
        if len(txt) < 3:
            raise NpuLibError("%s: expected 3 hex IOVAs" % iova_txt)
        old = [int(x, 16) for x in txt[:3]]
        return cls(asset_dir=asset_dir, old_a=old[0], old_b=old[1], old_c=old[2], **kw)

    def to_text(self):
        lines = [
            "# npu_run plan -- generated by npu_lib; key=value only.",
            "# address words in the command stream are (iova >> 4); relocation matches by value.",
            "asset_dir=%s" % self.asset_dir,
            "old_a=0x%x" % self.old_iova[0],
            "old_b=0x%x" % self.old_iova[1],
            "old_c=0x%x" % self.old_iova[2],
            "alloc_a=%d" % self.alloc[0],
            "alloc_b=%d" % self.alloc[1],
            "alloc_c=%d" % self.alloc[2],
            "dir0=%d" % self.dir[0],
            "dir1=%d" % self.dir[1],
            "dir2=%d" % self.dir[2],
            "patch_idx=%d" % self.patch_idx,
            "expect_patches=%d" % self.expect_patches,
            "bytes_a=%d" % self.bytes_a,
            "bytes_b=%d" % self.bytes_b,
            "bytes_out=%d" % self.bytes_out,
            "n_inputs=%d" % self.n_inputs,
            "in_a=%s" % self.in_a,
            "in_b=%s" % self.in_b,
            "out=%s" % self.out,
        ]
        if self.extra_file:
            lines.append("extra_file=%s" % self.extra_file)
        return "\n".join(lines) + "\n"

    def write(self, path):
        Path(path).write_text(self.to_text())
        return path
